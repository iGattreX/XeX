// Generates src/styles.src.css: the design tokens (CSS variables, light + dark), the brand override
// block and the shared component classes.
// Run by `npm run build`; compiled to dist/styles.css (which resolves the @apply rules).
import fs from 'node:fs'

// ---------------------------------------------------------------------------------------------
// Brand utilities re-declared as direct var() lookups (see the comment in the output below).
// ---------------------------------------------------------------------------------------------
const all = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900]
const rng = (a, b) => all.filter((s) => s >= a && s <= b)
const rules = []
const add = (sel, decl) => rules.push(`${sel} { ${decl} }`)

for (const s of rng(50, 900)) add(`.bg-brand-${s}`, `background-color: var(--brand-${s}) !important;`)
for (const s of rng(500, 800)) add(`.text-brand-${s}`, `color: var(--brand-${s}) !important;`)
for (const s of rng(200, 600)) add(`.border-brand-${s}`, `border-color: var(--brand-${s}) !important;`)
for (const s of rng(200, 400)) add(`.ring-brand-${s}`, `--tw-ring-color: var(--brand-${s}) !important;`)
for (const s of [50, 100, 600, 700]) add(`.hover\\:bg-brand-${s}:hover`, `background-color: var(--brand-${s}) !important;`)
for (const s of [600, 700, 800]) add(`.hover\\:text-brand-${s}:hover`, `color: var(--brand-${s}) !important;`)
for (const s of [300, 400, 500]) add(`.hover\\:border-brand-${s}:hover`, `border-color: var(--brand-${s}) !important;`)
add(
  `.focus\\:ring-brand-400:focus, .focus-visible\\:ring-brand-400:focus-visible, .focus-within\\:ring-brand-400:focus-within`,
  `--tw-ring-color: var(--brand-400) !important;`,
)
add(`.focus\\:border-brand-400:focus`, `border-color: var(--brand-400) !important;`)
add(`.group:focus-visible .group-focus-visible\\:ring-brand-400`, `--tw-ring-color: var(--brand-400) !important;`)
for (const s of [50, 100, 500, 600])
  add(
    `.from-brand-${s}`,
    `--tw-gradient-from: var(--brand-${s}) !important; --tw-gradient-stops: var(--tw-gradient-from), var(--tw-gradient-to, rgb(255 255 255 / 0)) !important;`,
  )
for (const s of [100, 600, 700, 800]) add(`.to-brand-${s}`, `--tw-gradient-to: var(--brand-${s}) !important;`)

// ---------------------------------------------------------------------------------------------
// Semantic tokens. Components use these (bg-surface, text-accent, bg-danger-soft …) or the
// remapped gray scale, so dark mode is a change of variable values, never a list of overrides.
// ---------------------------------------------------------------------------------------------
const tone = (name, solid, light, dark) => ({
  light: `  --${name}: ${solid}; --${name}-soft: ${light[0]}; --${name}-line: ${light[1]}; --${name}-ink: ${light[2]};`,
  dark: `  --${name}-soft: ${dark[0]}; --${name}-line: ${dark[1]}; --${name}-ink: ${dark[2]};`,
})
const tones = [
  tone('danger', '#ef4444', ['#fee2e2', '#fecaca', '#b91c1c'], ['#4a1a22', '#7f1d1d', '#fca5a5']),
  tone('success', '#10b981', ['#d1fae5', '#a7f3d0', '#047857'], ['#0c3a2c', '#14532d', '#6ee7b7']),
  tone('warning', '#f59e0b', ['#fef3c7', '#fde68a', '#b45309'], ['#4a3410', '#78350f', '#fcd34d']),
  tone('info', '#0ea5e9', ['#e0f2fe', '#bae6fd', '#0369a1'], ['#0c3350', '#075985', '#7dd3fc']),
  tone('purple', '#a855f7', ['#f3e8ff', '#e9d5ff', '#7e22ce'], ['#3a1f5a', '#581c87', '#d8b4fe']),
]

const css = `/* Generated by scripts/gen-css.mjs — do not edit. Compiled to dist/styles.css at build time. */

/* ------------------------------------------------------------------ *
 * Tokens
 *
 * --brand-*  is written onto <html> at runtime by <ThemeProvider> (the fallback below is Classic,
 *            so the first paint is never unstyled).
 * --gray-*   the Tailwind gray scale is remapped to these (see @xex/tailwind-preset), so every
 *            gray-* utility flips automatically in dark mode.
 * the rest   semantic names used by components: surface, canvas, accent*, and the status tones
 *            danger / success / warning / info / purple (solid, -soft, -line, -ink).
 * ------------------------------------------------------------------ */
:root {
  --brand-50: #eff6ff; --brand-100: #dbeafe; --brand-200: #bfdbfe; --brand-300: #93c5fd; --brand-400: #60a5fa;
  --brand-500: #3b82f6; --brand-600: #2563eb; --brand-700: #1d4ed8; --brand-800: #1e40af; --brand-900: #1e3a8a;
  --font-sans: Inter, ui-sans-serif, system-ui, sans-serif;

  --gray-50: #f9fafb; --gray-100: #f3f4f6; --gray-200: #e5e7eb; --gray-300: #d1d5db; --gray-400: #9ca3af;
  --gray-500: #6b7280; --gray-600: #4b5563; --gray-700: #374151; --gray-800: #1f2937; --gray-900: #111827;
  --canvas: var(--gray-50);
  --surface: #ffffff;

  --accent: var(--brand-700);        /* text and icons in the brand colour (AA on accent-soft/softer in every theme) */
  --accent-strong: var(--brand-800);
  --accent-soft: var(--brand-50);    /* tinted backgrounds */
  --accent-softer: var(--brand-100);
  --accent-line: var(--brand-200);   /* tinted borders and rings */

${tones.map((t) => t.light).join('\n')}

  --ring-track: #e5e7eb;
  --overlay: rgb(255 255 255 / 0.65);
}

html[data-mode='dark'] {
  color-scheme: dark;
  /* Neutral greys (equal R, G, B): no blue cast. Brand colour only appears where a component asks for it. */
  --gray-50: #1b1b1b; --gray-100: #252525; --gray-200: #303030; --gray-300: #424242; --gray-400: #808080;
  --gray-500: #9a9a9a; --gray-600: #b8b8b8; --gray-700: #d0d0d0; --gray-800: #e6e6e6; --gray-900: #f4f4f4;
  --canvas: #0b0b0b;
  --surface: #161616;

  --accent: var(--brand-300);
  --accent-strong: var(--brand-200);
  --accent-soft: color-mix(in srgb, var(--brand-500) 16%, #0b0b0b);
  --accent-softer: color-mix(in srgb, var(--brand-500) 26%, #0b0b0b);
  --accent-line: color-mix(in srgb, var(--brand-500) 40%, #0b0b0b);

${tones.map((t) => t.dark).join('\n')}

  --ring-track: #333333;
  --overlay: rgb(22 22 22 / 0.65);
}

/* ------------------------------------------------------------------ *
 * Brand overrides (runtime theming)
 *
 * Tailwind compiles bg-brand-600 etc. at build time; relying on the
 * compiled output to repaint when --brand-* changes is not reliable
 * across every build setup. These plain-CSS rules use !important to
 * re-declare the brand utilities we use as direct var() lookups, so a
 * theme switch repaints immediately wherever this file is loaded.
 * They are the SOLID brand colours: for tinted backgrounds, accent text
 * and borders that must adapt to dark mode use the accent-* tokens.
 * (Opacity modifiers such as bg-brand-600/50 are not supported by var() colors.)
 * ------------------------------------------------------------------ */
${rules.join('\n')}

/* ------------------------------------------------------------------ *
 * Global conventions
 * ------------------------------------------------------------------ */
body { @apply font-sans antialiased; background-color: var(--canvas); color: var(--gray-900); }
input[type='checkbox'], input[type='radio'], input[type='range'] { accent-color: var(--brand-600); }

/* Default keyboard-focus ring, themed. :where() keeps specificity at zero, so any control that
   defines its own ring (focus-visible:ring-*, focus:outline-none) simply overrides this. */
:where(:focus-visible) { outline: 2px solid var(--brand-500); outline-offset: 2px; }
:where(html[data-mode='dark'] :focus-visible) { outline-color: var(--brand-300); }

.card { @apply bg-surface rounded-xl border border-gray-200 shadow-sm; }

.nav-item-active { @apply flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium text-white; background-color: var(--brand-600); }
.nav-item-inactive { @apply flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium text-gray-600 transition-colors hover:bg-gray-100 hover:text-gray-900; }

.stat-indigo { @apply border; background-color: var(--accent-soft); color: var(--accent); border-color: var(--accent-line); }
.stat-emerald { @apply border; background-color: var(--success-soft); color: var(--success-ink); border-color: var(--success-line); }
.stat-amber { @apply border; background-color: var(--warning-soft); color: var(--warning-ink); border-color: var(--warning-line); }
.stat-rose { @apply border; background-color: var(--danger-soft); color: var(--danger-ink); border-color: var(--danger-line); }
.stat-sky { @apply border; background-color: var(--info-soft); color: var(--info-ink); border-color: var(--info-line); }

.weight-pill { @apply inline-flex min-w-[1.5rem] items-center justify-center rounded-md bg-gray-100 px-1.5 py-0.5 text-xs font-semibold tabular-nums text-gray-700; }

/* LoadingDots */
@keyframes xex-dot-fade { 0%, 80%, 100% { opacity: 0.2; } 40% { opacity: 1; } }
.xex-dots { display: inline-flex; align-items: center; gap: 3px; vertical-align: middle; }
.xex-dots > i { width: 6px; height: 6px; border-radius: 9999px; background: currentColor; opacity: 0.2; animation: xex-dot-fade 0.7s ease-in-out infinite; }
.xex-dots > i:nth-child(2) { animation-delay: 0.12s; }
.xex-dots > i:nth-child(3) { animation-delay: 0.24s; }

/* ProgressBar (indeterminate), ProgressRing track, LoadingOverlay scrim */
@keyframes xex-indeterminate { 0% { left: -40%; } 100% { left: 100%; } }
.xex-indeterminate { animation: xex-indeterminate 1.2s ease-in-out infinite; }
.xex-ring-track { stroke: var(--ring-track); }
.xex-overlay { background-color: var(--overlay); }
@media (prefers-reduced-motion: reduce) {
  .xex-dots > i { animation: none; opacity: 0.6; }
  .xex-indeterminate { animation: none; left: 0; width: 100%; opacity: 0.5; }
}
`
fs.writeFileSync(new URL('../src/styles.src.css', import.meta.url), css)
console.log('wrote src/styles.src.css')
